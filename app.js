let lang = localStorage.getItem("furat-language") || "en";
let activeService = "education";
const root = document.documentElement;
const langToggle = document.getElementById("langToggle");

/* ============================================================
   Language Rendering
   ============================================================ */
function renderLanguage() {
  root.lang = lang;
  root.dir = lang === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n;
    if (translations[lang][key]) {
      el.innerHTML = translations[lang][key];
    }
  });

  langToggle.classList.toggle("is-ar", lang === "ar");

  langToggle.setAttribute(
    "aria-label",
    lang === "en" ? "Switch to Arabic" : "التبديل إلى الإنجليزية"
  );

  renderService(activeService);
  localStorage.setItem("furat-language", lang);
}

